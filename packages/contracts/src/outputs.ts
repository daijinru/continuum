import { z, type ZodTypeAny } from "zod";
import { monitor } from "./monitor.ts";
const id = z.string().uuid(),
  str = z.string(),
  row = (shape: Record<string, ZodTypeAny>) => z.object(shape).passthrough();
const provider = z.enum(["demo", "codex"]),
  status = z.enum([
    "queued",
    "starting",
    "running",
    "waiting_approval",
    "succeeded",
    "failed",
    "interrupted",
    "unknown",
  ]);
const goal = row({
    id,
    title: str,
    description: str,
    workspace_id: id,
    provider,
    state: str,
    criteria: str,
    constraints_json: str,
  }),
  run = row({
    id,
    goal_id: id,
    provider,
    status,
    thread_id: str.nullable(),
    turn_id: str.nullable(),
    created: str,
  }),
  event = row({
    id,
    goal_id: id,
    run_id: id,
    seq: z.number().int(),
    type: str,
    received: str,
    method: str,
    payload: str,
  });
const story = row({
  id,
  goal_id: id,
  title: str,
  version: z.number(),
  verification: z.enum(["reported", "verified", "unverified", "disputed"]),
  materiality: z.number().min(0).max(1),
});
const item = row({
  id,
  run_id: id,
  goal_id: id,
  request_id: str,
  action: str,
  kind: z.enum(["approval", "input", "decision"]),
  status: str,
  version: z.number().int(),
});
const schedule = row({ id, goal_id: id, next_at: str, state: str }),
  file = row({
    id,
    goal_id: id,
    run_id: id,
    path: str,
    verified: str.nullable(),
  });
const report = row({
  id,
  goal_id: id,
  run_id: id,
  title: str,
  summary: str,
  updated: str,
});
const briefing = row({
  id,
  generated: str,
  count: z.number(),
  quiet: z.boolean(),
  reports: z.array(report).optional(),
  sections: z.object({
    needs: z.array(row({ id })),
    outcomes: z.array(story),
    changes: z.array(story),
    insights: z.array(story),
    next: z.array(row({ id })),
  }),
});
const workspace = row({ id, path: str, enabled: z.number() }),
  connection = row({ id: provider, state: str, detail: str }),
  cfg = row({
    dailyTime: str,
    budget: z.number(),
    cooldown: z.number(),
    maxMinutes: z.number(),
  });
const count = z.number().int().nonnegative().nullable();
const usage = z.object({ input: count, output: count, total: count });
export const outputs: Record<string, ZodTypeAny> = {
  "GET /conversation": z.array(
    row({
      id,
      seq: z.number().int(),
      role: z.enum(["user", "assistant"]),
      kind: str,
      body: str,
      created: str,
      refs: z.array(row({ id, title: str })),
    }),
  ),
  "POST /conversation/messages": row({ id }),
  "POST /conversation/projects/:id": row({ id }),
  "POST /conversation/directories/:id": row({ id }),
  "GET /session": row({ token: str }),
  "GET /health": row({ ready: z.boolean(), instance: id }),
  "POST /system/restart": z.object({ instance: id, accepted: z.literal(true) }),
  "GET /system/status": row({
    db: str,
    worker: z.object({ lastTick: str.nullable(), error: str.nullable() }),
    connections: z.array(connection),
  }),
  "GET /system/monitor": monitor,
  "GET /agent-connections": z.array(connection),
  "POST /agent-connections/check": row({
    installed: z.boolean(),
    ready: z.boolean(),
    version: str,
    detail: str,
  }),
  "GET /settings": cfg.extend({
    usage: z.object({ conversation: usage, goals: usage, all: usage }),
    service: z.object({ instance: id, canRestart: z.boolean(), canChooseFolder: z.boolean() }),
  }),
  "PATCH /settings": cfg,
  "POST /workspaces": workspace,
  "POST /workspaces/choose-folder": row({ path: str }),
  "PATCH /workspaces/:id": row({ id, enabled: z.boolean() }),
  "GET /goals": z.array(goal),
  "GET /goals/:id": goal.extend({ usage }),
  "PATCH /goals/:id": goal,
  "POST /goals": goal,
  "POST /commissions": goal,
  "POST /goals/:id/preferences": goal,
  "GET /goals/:id/reports": z.array(report),
  "POST /goals/:id/pause": goal,
  "POST /goals/:id/resume": goal,
  "POST /goals/:id/check": row({ criterion: str, checked: z.boolean() }),
  "POST /goals/:id/start": run,
  "POST /goals/:id/interrupt": run,
  "POST /runs/:id/reconcile": run,
  "GET /goals/:id/runs": z.array(run),
  "GET /runs/:id": run,
  "GET /runs/:id/events": z.array(event),
  "GET /runs/:id/artifacts": z.array(file),
  "GET /stories": z.array(story),
  "GET /stories/:id": story,
  "GET /stories/:id/events": z.array(event),
  "GET /briefings": z.array(briefing),
  "GET /briefings/:id": briefing,
  "POST /briefings/generate": briefing,
  "POST /briefings/:id/acknowledge": row({
    seq: z.number(),
    reviewed: str.nullable(),
  }),
  "GET /inbox": z.array(item),
  "GET /inbox/:id": item,
  "POST /inbox/:id/decision": item,
  "GET /activity": z.array(event),
  "GET /events/:id": event,
  "POST /goals/:id/schedules": schedule,
  "PATCH /goals/:id/limits": cfg,
  "POST /schedules/:id/stop": row({ id }),
  "POST /chat/messages": row({
    id,
    goal_id: id,
    scope: str,
    ref: str,
    content: str,
    status: str,
  }),
};
